  function getLang() { return lang; }
  function setLang(l) {
    lang = (l === 'en') ? 'en' : 'zh';
    try { Platform.saveSetting('lang', lang); } catch (_) {}
  }
  function toggleLang() {
    setLang(lang === 'zh' ? 'en' : 'zh');
    return lang;
  }
  function init() {
    const saved = Platform.loadSetting('lang');
    if (saved === 'en' || saved === 'zh') lang = saved;
  }
  function t(key, vars) {
    const dict = UI[lang] || UI.zh;
    let str = dict[key];
    if (str === undefined) str = UI.en[key] || key;
    if (vars && typeof str === 'string') {
      Object.keys(vars).forEach(k => {
        str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
      });
    }
    return str;
  }
  function pick(obj) {
    if (!obj) return '';
    if (typeof obj === 'string') return obj;
    return obj[lang] || obj.zh || obj.en || '';
  }

  return { UI, init, getLang, setLang, toggleLang, t, pick };
